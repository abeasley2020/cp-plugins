"""Script half of the CP Course Quality Standard.

Each check returns results in the review format the three reviewer agents also
write (skills/cp-build/references/review-format.md):

    {"criterion": "D3", "target": "<lesson id or file>", "result": "pass|fail|warn|na",
     "evidence": "...", "fix": "...", "owner": "cp-lesson-writer", "checker": "script"}

A "fail" blocks the module. A "warn" goes to the ID and the reviewer agents.
"na" means the criterion does not apply to this target. Standard library only.
"""

import json
import os
import re
from html.parser import HTMLParser

from .lessonmd import INTERACTIONS, ITEM_TYPES, md_elements, options, parse_lesson, words

HERE = os.path.dirname(os.path.abspath(__file__))
STANDARD_PATH = os.path.join(HERE, "..", "..", "standard", "cp-quality-standard.json")

VAGUE_VERBS = {"understand", "know", "learn", "appreciate", "grasp", "be aware", "be familiar", "realize",
               "comprehend", "learn about", "become familiar"}
BLOOM = {"remember", "understand", "apply", "analyze", "evaluate", "create"}
BLOOM_RANK = {b: i for i, b in enumerate(["remember", "understand", "apply", "analyze", "evaluate", "create"])}

BANNED_PHRASES = [
    "it is important to note", "it's important to note", "in this lesson we will", "in this lesson, we will",
    "in this module we will", "let's dive", "let us dive", "dive into", "delve", "in today's fast-paced",
    "in today's world", "key takeaways", "at the end of the day", "unlock the power", "game-changer",
    "game changer", "navigate the complexities", "a testament to", "plays a crucial role", "plays a vital role",
    "seamlessly", "embark on", "journey of discovery", "rich tapestry", "furthermore,", "moreover,",
    "in conclusion,", "it goes without saying", "needless to say", "harness the power", "elevate your",
]
EMOJI_RE = re.compile("[\U0001F300-\U0001FAFF\U00002600-\U000027BF\U0001F000-\U0001F2FF\U0001F900-\U0001F9FF]")
SCIENTIFIC_KINDS = {"diagram", "graph", "chart", "process", "structure", "framework", "map", "table", "flow"}
AI_IMAGE_HINTS = re.compile(r"(midjourney|dall-?e|stable diffusion|firefly|ai[- ]generated|generated by ai|imagen)", re.I)
SMALL_WORDS = {"a", "an", "and", "as", "at", "but", "by", "for", "in", "of", "on", "or", "the", "to", "vs", "with",
               "from", "into", "is", "are", "be", "per", "via"}

TARGETS = {"core_words": (600, 900), "minutes": (10, 15), "items": (3, 5), "video_target": 6, "video_max": 10,
           "para_run": 5, "alt_max": 125, "heading_max": 120, "image_kb": 400}


def load_standard():
    with open(STANDARD_PATH, encoding="utf-8") as fh:
        return json.load(fh)


_STD = None


def owner(cid):
    global _STD
    if _STD is None:
        _STD = {c["id"]: c for c in load_standard()["criteria"]}
    return (_STD.get(cid) or {}).get("owner", "cp-lesson-writer")


def res(cid, target, result, evidence, fix=""):
    return {"criterion": cid, "target": target, "result": result, "evidence": evidence, "fix": fix,
            "owner": owner(cid), "checker": "script"}

# ---------------------------------------------------------------- html model

class Page(HTMLParser):
    """Collects what the static checks need from a rendered page."""

    VOID = {"img", "input", "br", "hr", "meta", "link", "source", "area", "col", "embed", "track", "wbr"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.headings = []      # (level, text)
        self.imgs = []          # attrs
        self.links = []         # (href, text)
        self.styles = 0
        self.style_tags = 0
        self.ext = []           # external resources
        self.tables = []        # {"caption": bool, "th": n, "th_scope": n}
        self.inputs = []        # (id, type)
        self.label_for = set()
        self.text = []          # body text chunks, outside code and script
        self.lang = None
        self.main = 0
        self._stack = []
        self._h = None
        self._a = None
        self._skip = 0
        self._table = None
        self.ids = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if "style" in a:
            self.styles += 1
        if a.get("id"):
            self.ids.append(a["id"])
        if tag == "html":
            self.lang = a.get("lang")
        if tag == "style":
            self.style_tags += 1
        if tag == "main":
            self.main += 1
        if tag in ("script", "style", "code", "pre"):
            self._skip += 1
        for attr in ("src", "href"):
            v = a.get(attr) or ""
            if re.match(r"^(https?:)?//", v) and tag in ("script", "link", "img", "iframe", "source", "video", "audio"):
                self.ext.append(f"<{tag} {attr}={v}>")
        if tag == "link" and a.get("rel") == "stylesheet" and not re.match(r"^(https?:)?//", a.get("href", "")):
            pass
        if re.fullmatch(r"h[1-6]", tag):
            self._h = [int(tag[1]), ""]
        if tag == "img":
            self.imgs.append(a)
        if tag == "a":
            self._a = [a.get("href", ""), ""]
        if tag == "table":
            self._table = {"caption": False, "th": 0, "th_scope": 0}
        if tag == "caption" and self._table is not None:
            self._table["caption"] = True
        if tag == "th" and self._table is not None:
            self._table["th"] += 1
            if a.get("scope") in ("col", "row", "colgroup", "rowgroup"):
                self._table["th_scope"] += 1
        if tag in ("input", "select", "textarea") and a.get("type") not in ("hidden", "submit", "reset", "button"):
            self.inputs.append((a.get("id"), a.get("type", tag)))
        if tag == "label" and a.get("for"):
            self.label_for.add(a["for"])
        if tag not in self.VOID:
            self._stack.append(tag)

    def handle_endtag(self, tag):
        if tag in ("script", "style", "code", "pre") and self._skip:
            self._skip -= 1
        if re.fullmatch(r"h[1-6]", tag) and self._h:
            self.headings.append((self._h[0], " ".join(self._h[1].split())))
            self._h = None
        if tag == "a" and self._a is not None:
            self.links.append((self._a[0], " ".join(self._a[1].split())))
            self._a = None
        if tag == "table" and self._table is not None:
            self.tables.append(self._table)
            self._table = None
        if self._stack and self._stack[-1] == tag:
            self._stack.pop()

    def handle_data(self, data):
        if self._h is not None:
            self._h[1] += data
        if self._a is not None:
            self._a[1] += data
        if not self._skip:
            self.text.append(data)


def parse_html(text):
    p = Page()
    p.feed(text)
    return p

# ---------------------------------------------------------------- helpers

def item_blocks(lesson):
    return [b for b in lesson["blocks"] if b["type"] in ITEM_TYPES]


def core_word_count(lesson):
    """Words of explanation: Markdown prose plus the text of teaching blocks,
    not counting items, reflections or optional depth."""
    n = 0
    skip = ITEM_TYPES | {"reflect", "depth", "video", "practice"}
    for b in lesson["blocks"]:
        if b["type"] == "md":
            if b["t"] == "p":
                n += words(b["text"])
            elif b["t"] in ("ul", "ol"):
                n += sum(words(i) for i in b["items"])
        elif b["type"] not in skip and b["type"] != "continue":
            body = [l for l in b["lines"] if not re.match(r"^\s*(src|alt|credit|layout|kind|caption|Description):", l)]
            n += words(" ".join(body))
    return n


def estimate_minutes(lesson):
    w = core_word_count(lesson)
    reading = w / 200.0
    inter = sum(1.5 for b in lesson["blocks"] if b["type"] in INTERACTIONS | {"recall", "worked"})
    video = sum(float(b["args"].get("minutes", 0) or 0) for b in lesson["blocks"] if b["type"] == "video")
    reflect = sum(2 for b in lesson["blocks"] if b["type"] == "reflect")
    return round(reading + inter + video + reflect, 1)


def objective_ids(meta):
    out = []
    for o in meta.get("objectives") or []:
        if isinstance(o, dict):
            out.append(str(o.get("id", "")))
    return [o for o in out if o]


def first_verb(text):
    t = re.sub(r"^(to|be able to)\s+", "", (text or "").strip().lower())
    return t.split(" ")[0] if t else ""


def sentence_case_ok(text):
    toks = [t for t in re.findall(r"[A-Za-z][A-Za-z'-]*", text)]
    if len(toks) < 3:
        return True
    rest = [t for t in toks[1:] if t.lower() not in SMALL_WORDS]
    if not rest:
        return True
    caps = [t for t in rest if t[0].isupper() and not t.isupper()]
    return len(caps) <= len(rest) / 2 or len(caps) <= 1


def skeleton(lesson):
    seq = []
    for b in lesson["blocks"]:
        t = b["type"]
        if t == "md":
            t = "h2" if b["t"] == "h" and b["level"] == 2 else ("p" if b["t"] == "p" else None)
        if t and (not seq or seq[-1] != t):
            seq.append(t)
    return tuple(seq)

# ---------------------------------------------------------------- lesson checks

def check_lesson(lesson, page_html, ctx=None):
    ctx = ctx or {}
    meta = lesson["meta"]
    lid = str(meta.get("id") or os.path.basename(lesson["path"]))
    blocks = lesson["blocks"]
    out = []
    page = parse_html(page_html) if page_html else None
    body_text = " ".join(page.text) if page else ""
    module_no = int(meta.get("module") or ctx.get("module") or 1)

    # R1 objectives: observable verb and Bloom level
    objs = meta.get("objectives") or []
    bad = []
    for o in objs:
        text = o.get("text", "") if isinstance(o, dict) else str(o)
        bl = (o.get("bloom", "") if isinstance(o, dict) else "").lower()
        v = first_verb(text)
        if v in VAGUE_VERBS or any(text.lower().startswith(x) for x in VAGUE_VERBS):
            bad.append(f'"{text}" opens with a vague verb')
        if bl not in BLOOM:
            bad.append(f'"{text}" has no Bloom level')
    if not objs:
        out.append(res("R1", lid, "fail", "The lesson lists no objectives.", "Add 1 to 3 objectives from the approved blueprint."))
    elif bad:
        out.append(res("R1", lid, "fail", "; ".join(bad), "Use an observable verb and name the Bloom level."))
    elif len(objs) > 3:
        out.append(res("R1", lid, "fail", f"{len(objs)} objectives; a lesson serves 1 to 3.", "Split the lesson or move objectives."))
    else:
        out.append(res("R1", lid, "pass", f"{len(objs)} objective(s), each with an observable verb and a Bloom level."))

    # R4 script half: item Bloom level against objective Bloom level
    ob = {str(o.get("id")): (o.get("bloom") or "").lower() for o in objs if isinstance(o, dict)}
    low = []
    for b in item_blocks(lesson):
        o = b["args"].get("objective")
        ib = (b["args"].get("bloom") or "").lower()
        if o in ob and ib in BLOOM_RANK and ob[o] in BLOOM_RANK and BLOOM_RANK[ib] < BLOOM_RANK[ob[o]]:
            low.append(f"{b['type']} on line {b['line']} is {ib}, objective {o} is {ob[o]}")
    for o, lvl in ob.items():
        if lvl in BLOOM_RANK and BLOOM_RANK[lvl] >= BLOOM_RANK["apply"]:
            hits = [b for b in item_blocks(lesson) if b["args"].get("objective") == o and
                    BLOOM_RANK.get((b["args"].get("bloom") or "").lower(), -1) >= BLOOM_RANK["apply"]]
            if not hits:
                low.append(f"objective {o} is {lvl} but no item reaches apply or higher")
    out.append(res("R4", lid, "fail" if low else "pass", "; ".join(low) or "Item levels match or exceed their objectives.",
                   "Raise the item to the objective's level (a scenario or applied check)." if low else ""))

    # R5 sources and gap markers
    srcs = meta.get("sources") or []
    gaps = re.findall(r"\[GAP:[^\]]*\]", "\n".join(
        [b.get("text", "") for b in blocks if b["type"] == "md"] + ["\n".join(b.get("lines", [])) for b in blocks if b["type"] != "md"]))
    if not srcs:
        out.append(res("R5", lid, "fail", "No sources in front matter.", "List each faculty file with slide or page numbers."))
    elif gaps:
        out.append(res("R5", lid, "warn", f"{len(gaps)} gap marker(s) for faculty: " + "; ".join(g[5:-1].strip() for g in gaps[:5]),
                       "Resolve with faculty before Gate 3. Do not fill the gap in."))
    else:
        out.append(res("R5", lid, "pass", f"{len(srcs)} source line(s), no open gaps. Rigor agent spot checks claims."))

    # R7 feedback on every item
    missing = []
    for b in item_blocks(lesson):
        if b["type"] in ("check", "scenario"):
            _, opts = options(b["lines"])
            if len(opts) < 2:
                missing.append(f"{b['type']} on line {b['line']} has fewer than two options")
            for o in opts:
                if not o["why"]:
                    missing.append(f"option \"{o['text'][:40]}\" on line {b['line']} has no Why")
        elif b["type"] == "recall":
            if "Model answer:" not in "\n".join(b["lines"]):
                missing.append(f"recall on line {b['line']} has no model answer")
        elif b["type"] == "sorting":
            rows = [l for l in b["lines"] if "=>" in l]
            whys = [l for l in b["lines"] if l.strip().startswith("Why:")]
            if len(whys) < len(rows):
                missing.append(f"sorting on line {b['line']} explains {len(whys)} of {len(rows)} items")
    out.append(res("R7", lid, "fail" if missing else "pass", "; ".join(missing) or "Every option and item explains itself.",
                   "Write why the right answer is right and why each distractor falls short." if missing else ""))

    # R8 minutes and core words
    cw = core_word_count(lesson)
    mins = estimate_minutes(lesson)
    lo, hi = TARGETS["core_words"]
    mlo, mhi = TARGETS["minutes"]
    notes = []
    if cw < lo or cw > hi:
        notes.append(f"core explanation is {cw} words (target {lo} to {hi})")
    if mins < mlo or mins > mhi:
        notes.append(f"estimated {mins} minutes (target {mlo} to {mhi})")
    stated = meta.get("minutes")
    if stated and abs(float(stated) - mins) > 3:
        notes.append(f"front matter says {stated} minutes, estimate is {mins}")
    out.append(res("R8", lid, "warn" if notes else "pass", "; ".join(notes) or f"{cw} words, about {mins} minutes.",
                   "If the source is thin, record a gap for faculty rather than padding. If long, split at a concept boundary." if notes else ""))

    if page:
        # D1 no inline styles, one shared stylesheet
        d1 = []
        if page.styles:
            d1.append(f"{page.styles} style attribute(s)")
        if page.style_tags:
            d1.append(f"{page.style_tags} <style> element(s)")
        out.append(res("D1", lid, "fail" if d1 else "pass", "; ".join(d1) or "No inline styles; shared stylesheet only.",
                       "Move styling into cp-lesson.css as a class." if d1 else ""))

        # D3 static structure (axe and contrast run in scripts/axe.mjs)
        d3 = []
        h1 = [h for h in page.headings if h[0] == 1]
        if len(h1) != 1:
            d3.append(f"{len(h1)} h1 elements (need exactly one)")
        elif h1[0][1] != str(meta.get("title", h1[0][1])):
            d3.append("the h1 does not match the lesson title")
        prev = 0
        for lvl, txt in page.headings:
            if prev and lvl > prev + 1:
                d3.append(f'heading "{txt[:50]}" skips from h{prev} to h{lvl}')
            prev = lvl
            if len(txt) > TARGETS["heading_max"]:
                d3.append(f'heading "{txt[:50]}..." is {len(txt)} characters')
            if not txt.strip():
                d3.append(f"an empty h{lvl} heading")
            if txt.endswith("?"):
                d3.append(f'heading "{txt[:50]}" is a question')
        for a in page.imgs:
            alt = a.get("alt")
            if alt is None:
                d3.append(f"image {a.get('src')} has no alt attribute")
            elif len(alt) > TARGETS["alt_max"]:
                d3.append(f"image {a.get('src')} alt is {len(alt)} characters")
        for t in page.tables:
            if not t["caption"]:
                d3.append("a table has no caption")
            if t["th"] == 0 or t["th_scope"] < t["th"]:
                d3.append("a table header cell has no scope")
        for href, txt in page.links:
            if re.fullmatch(r"(click here|here|read more|more|link|this link)", txt.strip().lower()):
                d3.append(f'link text "{txt}" does not describe the destination')
            if re.match(r"^https?://", txt.strip()):
                d3.append(f"bare URL used as link text: {txt[:60]}")
        for i, typ in page.inputs:
            if not i or i not in page.label_for:
                d3.append(f"a {typ} control has no label")
        if page.lang != "en":
            d3.append("html lang is not en")
        if page.main != 1:
            d3.append("the page needs exactly one main landmark")
        dup = {x for x in page.ids if page.ids.count(x) > 1}
        if dup:
            d3.append("duplicate ids: " + ", ".join(sorted(dup)[:5]))
        out.append(res("D3", lid, "fail" if d3 else "pass",
                       "; ".join(d3) or "Static structure passes. Run axe for contrast, focus and target size.",
                       "Fix each item; the accessibility checks block delivery." if d3 else ""))

        # D7 no outside resources
        out.append(res("D7", lid, "fail" if page.ext else "pass",
                       "Outside resources: " + "; ".join(page.ext[:5]) if page.ext else
                       "No outside scripts, fonts or images. Components work with scripts off by design.",
                       "Copy the file into the package and use a relative path." if page.ext else ""))

        # D8 house style
        d8 = []
        if chr(0x2014) in page_html:
            d8.append(f"{page_html.count(chr(0x2014))} em-dash(es)")
        bangs = re.findall(r"[A-Za-z]!(?=\s|$)", body_text)
        if bangs:
            d8.append(f"{len(bangs)} exclamation point(s) in body copy")
        for ph in ("click here", "see below", "see above"):
            if ph in body_text.lower():
                d8.append(f'"{ph}"')
        notsc = [t for l, t in page.headings if l >= 2 and not sentence_case_ok(t)]
        if notsc:
            d8.append("headings not in sentence case: " + "; ".join(f'"{t[:40]}"' for t in notsc[:4]))
        out.append(res("D8", lid, "fail" if d8 else "pass", "; ".join(d8) or "House style holds.",
                       "Use a colon, period or parentheses for dashes; sentence case for headings." if d8 else ""))

    # D4 layout rhythm
    run, worst, two_col = 0, 0, False
    for b in blocks:
        if b["type"] == "md" and b["t"] in ("p", "ul", "ol"):
            run += 1
            worst = max(worst, run)
        elif b["type"] == "md" and b["t"] == "h":
            continue
        elif b["type"] == "continue":
            continue
        else:
            run = 0
        if b["type"] == "compare" or (b["type"] == "figure" and re.search(r"^\s*Text:|^\s*layout:\s*split", "\n".join(b["lines"]), re.M)):
            two_col = True
    d4 = []
    if worst > TARGETS["para_run"]:
        d4.append(f"{worst} paragraphs in a row without a figure, callout or interaction")
    if not two_col:
        d4.append("no two-column block (split figure or compare)")
    out.append(res("D4", lid, "fail" if worst > TARGETS["para_run"] else ("warn" if d4 else "pass"),
                   "; ".join(d4) or f"Longest prose run is {worst}; a two-column block is present.",
                   "Break the run with a figure, statement or interaction drawn from the source." if d4 else ""))

    # D6 images: credit, no AI photos, size
    d6, d6w = [], []
    for b in blocks:
        if b["type"] not in ("figure", "labeled-graphic"):
            continue
        txt = "\n".join(b["lines"])
        src = (re.search(r"^\s*src:\s*(.*)$", txt, re.M) or [None, ""])[1].strip()
        credit = (re.search(r"^\s*credit:\s*(.*)$", txt, re.M) or [None, ""])[1].strip()
        if AI_IMAGE_HINTS.search(txt):
            d6.append(f"figure on line {b['line']} looks like an AI-generated image")
        if src.startswith("placeholder:") or not src:
            d6w.append(f"figure on line {b['line']} is a placeholder")
            continue
        if not credit:
            d6.append(f"figure {src} has no credit line")
        base = ctx.get("asset_root") or os.path.dirname(lesson["path"])
        f = os.path.join(base, src)
        if os.path.isfile(f) and os.path.getsize(f) > TARGETS["image_kb"] * 1024:
            d6w.append(f"{src} is {os.path.getsize(f) // 1024} KB (budget {TARGETS['image_kb']} KB)")
    out.append(res("D6", lid, "fail" if d6 else ("warn" if d6w else "pass"), "; ".join(d6 + d6w) or "Every figure is credited and within budget.",
                   "Credit the source; replace AI images with a faculty image, an SVG from source or a licensed photo." if d6 + d6w else ""))

    # D9 script half: ban list counts
    d9, d9w = [], []
    low_text = (body_text or " ".join(b.get("text", "") for b in blocks if b["type"] == "md")).lower()
    hits = [p for p in BANNED_PHRASES if p in low_text]
    if hits:
        d9.append("banned phrases: " + ", ".join(f'"{h}"' for h in hits))
    if EMOJI_RE.search(body_text or ""):
        d9.append("emoji or decorative icons in the text")
    kinds = [b["type"] for b in blocks if b["type"] in INTERACTIONS]
    over = sorted({k for k in kinds if kinds.count(k) > 1 and k != "check"})
    if over:
        d9.append("more than one of: " + ", ".join(over))
    callouts = {"term", "caution", "statement", "quote", "depth"}
    seq = [b["type"] for b in blocks if b["type"] not in ("md", "continue")]
    stacked = [seq[i] for i in range(1, len(seq)) if seq[i] == seq[i - 1] and seq[i] in callouts]
    if stacked:
        d9.append("stacked identical callouts: " + ", ".join(sorted(set(stacked))))
    labelled = sum(1 for b in blocks if b["type"] in callouts | {"caution", "term"})
    if labelled > 4:
        d9w.append(f"{labelled} labeled callouts on one page")
    ph = sum(1 for b in blocks if b["type"] in ("figure", "labeled-graphic") and re.search(r"src:\s*placeholder:", "\n".join(b["lines"])))
    if ph:
        d9w.append(f"{ph} placeholder graphic(s); none may reach Gate 2")
    out.append(res("D9", lid, "fail" if d9 else ("warn" if d9w else "pass"), "; ".join(d9 + d9w) or
                   "Nothing from the ban list. Design agent compares the page against the reference lesson.",
                   "Rewrite in a colleague's voice; replace placeholders with real photos or course-style diagrams." if d9 + d9w else ""))

    # M2 lead-in before each figure
    m2 = []
    for i, b in enumerate(blocks):
        if b["type"] not in ("figure", "labeled-graphic"):
            continue
        prev = next((x for x in reversed(blocks[:i]) if x["type"] != "continue"), None)
        lead = prev is not None and prev["type"] == "md" and prev["t"] == "p"
        split = re.search(r"^\s*Text:", "\n".join(b["lines"]), re.M)
        if not lead and not split:
            m2.append(f"figure on line {b['line']} has no lead-in sentence before it")
    out.append(res("M2", lid, "fail" if m2 else "pass", "; ".join(m2) or "Every figure has a lead-in. Agent checks headings and first-use bold.",
                   "Add a sentence that says what to look for in the figure." if m2 else ""))

    # M3 long description under scientific figures, labels on the figure
    m3 = []
    for b in blocks:
        if b["type"] not in ("figure", "labeled-graphic"):
            continue
        txt = "\n".join(b["lines"])
        kind = (re.search(r"^\s*kind:\s*(\w+)", txt, re.M) or [None, "photo"])[1].lower()
        if (kind in SCIENTIFIC_KINDS or b["type"] == "labeled-graphic") and "Description:" not in txt:
            m3.append(f"{kind} figure on line {b['line']} has no long description")
    out.append(res("M3", lid, "fail" if m3 else "pass", "; ".join(m3) or "Long descriptions sit directly under each scientific figure.",
                   "Add a Description: section with every detail the alt text cannot carry." if m3 else ""))

    # M5 segmenting
    m5, m5w = [], []
    for b in blocks:
        if b["type"] == "video":
            m = float(b["args"].get("minutes", 0) or 0)
            if m > TARGETS["video_max"]:
                m5.append(f"video {b['args'].get('id', '')} is {m} minutes (max {TARGETS['video_max']})")
            elif m > TARGETS["video_target"]:
                m5w.append(f"video {b['args'].get('id', '')} is {m} minutes (target {TARGETS['video_target']})")
        if b["type"] == "md" and b["t"] == "ol" and len(b["items"]) > 4:
            m5.append(f"a plain numbered list of {len(b['items'])} steps in \"{b.get('section') or 'the lesson'}\"")
    out.append(res("M5", lid, "fail" if m5 else ("warn" if m5w else "pass"), "; ".join(m5 + m5w) or "Videos and processes are segmented.",
                   "Turn the list into a :::process block; split long videos." if m5 + m5w else ""))

    # M7 retrieval set at the end
    m7 = []
    idx = next((i for i, b in enumerate(blocks) if b["type"] == "md" and b["t"] == "h" and b["level"] == 2 and
                b["text"].lower().startswith("check your understanding")), None)
    if idx is None:
        m7.append('no "Check your understanding" section')
        set_items = []
    else:
        set_items = [b for b in blocks[idx:] if b["type"] in ITEM_TYPES]
        lo, hi = TARGETS["items"]
        if not lo <= len(set_items) <= hi:
            m7.append(f"retrieval set has {len(set_items)} items (need {lo} to {hi})")
        if not any(b["type"] == "recall" for b in set_items):
            m7.append("no free recall item in the set")
    cover = {b["args"].get("objective") for b in set_items}
    unc = [o for o in objective_ids(meta) if o not in cover]
    if unc:
        m7.append("objectives with no item in the set: " + ", ".join(unc))
    out.append(res("M7", lid, "fail" if m7 else "pass", "; ".join(m7) or f"{len(set_items)} items, a free recall, every objective covered.",
                   "End the lesson with 3 to 5 items tagged objective=, including one :::recall." if m7 else ""))

    # M8 spacing after module 1
    if module_no <= 1:
        out.append(res("M8", lid, "na", "Module 1 has no earlier module to space from."))
    else:
        spaced = [b for b in item_blocks(lesson) if b["args"].get("spaced_from")]
        types = {b["type"] for b in item_blocks(lesson)}
        m8 = []
        if not spaced:
            m8.append("no item from an earlier module (spaced_from=)")
        if len(types) < 2:
            m8.append("all items are one type")
        out.append(res("M8", lid, "fail" if m8 else "pass", "; ".join(m8) or "Spaced item present and item types mixed.",
                       "Add one item from an earlier module, tagged spaced_from=mNN." if m8 else ""))

    # A1 problem first
    first = next((b for b in blocks if not (b["type"] == "md" and b["t"] == "h") and b["type"] != "continue"), None)
    if first is None or first["type"] not in ("problem", "case"):
        out.append(res("A1", lid, "fail", f"the lesson opens with {first['type'] if first else 'nothing'}, not a problem or case",
                       "Open with :::problem or :::case from the faculty source, or a [GAP:] marker for faculty."))
    elif words(re.sub(r"\[GAP:[^\]]*\]", "", " ".join(first["lines"]))) < 25:
        out.append(res("A1", lid, "warn", "the opening problem is a gap marker for faculty", "Ask faculty for a real case."))
    else:
        out.append(res("A1", lid, "pass", "Opens with a problem or case. Agent judges whether it is real and from the field."))

    # A2 script half: report the opening word count for the agent
    if first is not None and first["type"] in ("problem", "case"):
        ow = words(" ".join(first["lines"]))
        out.append(res("A2", lid, "warn" if ow > 150 else "pass",
                       f"opening block is {ow} words. Agent checks it names who decides and the cost of getting it wrong.",
                       "Name the decision maker and the cost within the first 150 words." if ow > 150 else ""))

    # A4 optional depth labeled
    a4 = [b for b in blocks if b["type"] == "depth" and not (b["title"] or "Optional").lower().startswith("optional")]
    out.append(res("A4", lid, "fail" if a4 else ("pass" if any(b["type"] == "depth" for b in blocks) else "na"),
                   f"{len(a4)} depth block(s) not labeled Optional" if a4 else "Optional depth is labeled, or there is none.",
                   'Title depth blocks "Optional: ...".' if a4 else ""))

    # P1 draft marking
    final = str(meta.get("draft", "ai")).lower() == "final"
    if final and not meta.get("finalized_by"):
        out.append(res("P1", lid, "fail", "marked final with no finalizing ID recorded", "Add finalized_by: with the ID's initials."))
    else:
        out.append(res("P1", lid, "pass", "finalized by " + str(meta.get("finalized_by")) if final else "marked as a draft for ID review"))

    # P2 faculty-voiced text
    voiced = meta.get("faculty_voiced") or any(b["type"] == "video" for b in blocks)
    if not voiced:
        out.append(res("P2", lid, "na", "no faculty-voiced text"))
    elif meta.get("faculty_approval"):
        out.append(res("P2", lid, "pass", f"faculty approval recorded: {meta.get('faculty_approval')}"))
    else:
        stage = ctx.get("stage", "review")
        out.append(res("P2", lid, "fail" if stage == "package" else "warn", "faculty-voiced text has no recorded approval",
                       "Record faculty_approval: with the date before Gate 3."))
    return out

# ---------------------------------------------------------------- module checks

def check_module(lessons, module_dir, ctx=None):
    ctx = ctx or {}
    out = []
    tgt = os.path.basename(os.path.normpath(module_dir))
    # D9 skeletons across the module
    sk = [skeleton(l) for l in lessons]
    same = []
    for i in range(len(sk)):
        for j in range(i + 1, len(sk)):
            if sk[i] == sk[j]:
                same.append(f"{lessons[i]['meta'].get('id')} and {lessons[j]['meta'].get('id')}")
    if len(lessons) > 1:
        out.append(res("D9", tgt, "fail" if same else "pass",
                       "identical lesson skeletons: " + "; ".join(same) if same else f"{len(set(sk))} distinct skeletons across {len(lessons)} lessons.",
                       "Vary the block order and components to fit each lesson's content." if same else ""))
    # A3 landing page reflection
    landing = os.path.join(module_dir, "landing.md")
    if os.path.isfile(landing):
        lp = parse_lesson(open(landing, encoding="utf-8").read(), landing)
        has = any(b["type"] == "reflect" for b in lp["blocks"])
        out.append(res("A3", tgt, "pass" if has else "fail", "landing page has a reflection" if has else "landing page has no :::reflect block",
                       "" if has else "Ask learners to connect the module to their own work."))
    else:
        out.append(res("A3", tgt, "warn", "no landing.md in the module folder", "The lesson writer drafts the landing page."))
    # P3 build log
    log = os.path.join(module_dir, "build-log.csv")
    need = {"date", "step", "who", "id_hours", "producer_hours", "ai_assisted", "review_round"}
    if os.path.isfile(log):
        head = open(log, encoding="utf-8").readline().strip().lower().split(",")
        miss = need - {h.strip() for h in head}
        out.append(res("P3", tgt, "fail" if miss else "pass", "build log is missing columns: " + ", ".join(sorted(miss)) if miss else "build log present",
                       "Use the columns in references/review-format.md." if miss else ""))
    else:
        out.append(res("P3", tgt, "warn", "no build-log.csv yet", "cpb.py writes it; the ID adds hours."))
    # M8 cumulative mix
    return out


def check_css(css_text, target="cp-lesson.css"):
    """D2: Purdue tokens. #CC785C only on borders, gold never as text color."""
    bad = []
    for m in re.finditer(r"([a-z-]+)\s*:\s*([^;}{]+)", css_text, re.I):
        prop, val = m.group(1).lower(), m.group(2).lower()
        if "#cc785c" in val and not any(k in prop for k in ("border", "outline", "--")):
            bad.append(f"{prop}: {val.strip()}")
        if "#cfb991" in val and prop == "color":
            bad.append(f"gold as text color ({prop}: {val.strip()})")
    return [res("D2", target, "fail" if bad else "pass", "; ".join(bad) or "Purdue tokens only; coral #CC785C on borders, gold never text.",
                "Use #964F37 for small coral text." if bad else "")]

# ---------------------------------------------------------------- blueprint

def check_blueprint(bp, target="blueprint"):
    """R1 to R3 and R8 on a blueprint dict (see references/blueprint-format.md)."""
    out = []
    outcomes = bp.get("outcomes") or []
    objectives = bp.get("objectives") or []
    lessons = bp.get("lessons") or []
    assessments = bp.get("assessments") or []
    vague = []
    for o in outcomes + objectives:
        v = first_verb(o.get("text", ""))
        if v in VAGUE_VERBS or (o.get("bloom") or "").lower() not in BLOOM:
            vague.append(o.get("id", "?"))
    out.append(res("R1", target, "fail" if vague else "pass",
                   "vague verb or missing Bloom level: " + ", ".join(vague) if vague else "Every outcome and objective is observable with a Bloom level.",
                   "Rewrite with an observable verb and name the level." if vague else ""))
    oids = {o.get("id") for o in outcomes}
    orphan = [o.get("id") for o in objectives if not set(o.get("supports") or []) & oids]
    unsup = [x for x in oids if not any(x in (o.get("supports") or []) for o in objectives)]
    r2 = []
    if orphan:
        r2.append("objectives supporting no outcome: " + ", ".join(orphan))
    if unsup:
        r2.append("outcomes with no objective: " + ", ".join(sorted(unsup)))
    out.append(res("R2", target, "fail" if r2 else "pass", "; ".join(r2) or "Alignment is complete in both directions.",
                   "Fix the supports column in the blueprint." if r2 else ""))
    taught = {x for l in lessons for x in (l.get("objectives") or [])}
    measured = {x for a in assessments for x in (a.get("objectives") or [])}
    r3 = []
    for o in objectives:
        i = o.get("id")
        gaps = []
        if i not in taught:
            gaps.append("not taught")
        if i not in measured:
            gaps.append("not measured")
        if gaps:
            r3.append(f"{i} {' and '.join(gaps)}")
    out.append(res("R3", target, "fail" if r3 else "pass", "; ".join(r3) or "Every objective is taught, practiced in its lesson and measured.",
                   "Add a lesson or a graded assessment for each objective." if r3 else ""))
    hours = bp.get("credit_hours")
    mins = sum(float(l.get("minutes", 0) or 0) for l in lessons) + sum(float(a.get("minutes", 0) or 0) for a in assessments)
    if hours:
        expect = float(hours) * 45 * 60 / 1.0  # 45 learner hours per credit hour, in minutes
        ratio = mins / expect if expect else 0
        out.append(res("R8", target, "pass" if 0.85 <= ratio <= 1.15 else "warn",
                       f"planned {round(mins / 60, 1)} learner hours against {round(expect / 60)} expected for {hours} credit hour(s)",
                       "Adjust lesson scope or activity minutes with the ID." if not 0.85 <= ratio <= 1.15 else ""))
    else:
        out.append(res("R8", target, "warn", f"planned {round(mins / 60, 1)} learner hours; no credit hours given", "Add credit_hours to the blueprint."))
    return out

# ---------------------------------------------------------------- summary

def summarize(results):
    fails = [r for r in results if r["result"] == "fail"]
    warns = [r for r in results if r["result"] == "warn"]
    passes = [r for r in results if r["result"] == "pass"]
    return {"verdict": "fail" if fails else "pass", "fail": len(fails), "warn": len(warns), "pass": len(passes),
            "by_owner": {o: sum(1 for r in fails if r["owner"] == o) for o in sorted({r["owner"] for r in fails})}}


def to_markdown(results, title="Script checks"):
    s = summarize(results)
    lines = [f"# {title}", "", f"Verdict: **{s['verdict']}**. {s['fail']} fail, {s['warn']} warn, {s['pass']} pass.", "",
             "| Criterion | Target | Result | Evidence | Fix | Owner |", "|---|---|---|---|---|---|"]
    order = {"fail": 0, "warn": 1, "pass": 2, "na": 3}
    for r in sorted(results, key=lambda r: (order.get(r["result"], 4), r["criterion"])):
        cell = lambda x: str(x).replace("|", "/").replace("\n", " ")
        lines.append(f"| {r['criterion']} | {cell(r['target'])} | {r['result']} | {cell(r['evidence'])} | {cell(r['fix'])} | {r['owner']} |")
    return "\n".join(lines) + "\n"
